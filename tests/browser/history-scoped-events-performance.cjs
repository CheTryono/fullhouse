'use strict';
const { chromium } = require('playwright'), assert = require('node:assert/strict'), { start } = require('../../scripts/serve-history-lab.cjs');
(async () => {
    const { server, url } = await start();
    let browser;
    try {
        browser = await chromium.launch({ executablePath: process.env.FULLHOUSE_CHROMIUM || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--enable-precise-memory-info', '--js-flags=--expose-gc'] });
        const context = await browser.newContext({ timezoneId: 'UTC' }), page = await context.newPage(), errors = [];
        page.on('pageerror', e => errors.push(e.message));
        await context.addInitScript(() => { for (const k of ['getItem', 'setItem', 'removeItem', 'clear'])
            Storage.prototype[k] = () => { throw Error('Public storage prohibited'); }; });
        await page.goto(url + '/storage');
        const result = await page.evaluate(async () => {
            // Same deterministic 64 JPEG + PNG corpus as B.2, generated by the same Chromium.
            const H = FullhouseHistory, L = H.schedule.validData, now = () => performance.now(), heapSample = () => performance.memory ? { usedJSHeapSize: performance.memory.usedJSHeapSize, totalJSHeapSize: performance.memory.totalJSHeapSize } : null, copy = x => JSON.parse(JSON.stringify(x)), doc = copy(H.scenarios(H).list.find(s => s.id === 'edited').doc), template = copy(Object.values(doc.logs)[0]);
            doc.logs = {};
            for (let i = 0; i < 5000; i++) {
                const date = new Date(Date.UTC(2030, 0, 7 + i)).toISOString().slice(0, 10), log = copy(template);
                log.evidences = [];
                Object.assign(log.history.capture, { executionId: 'execution-' + i, scheduledDate: date, capturedAt: date + 'T12:00:00Z' });
                log.history.state.lastRecordedAt = date + 'T12:00:00Z';
                if (log.completed)
                    log.history.state.completedRecordedAt = date + 'T12:00:00Z';
                doc.logs['e@' + date] = log;
            }
            for (let i = 0; i < 500; i++) {
                const r = copy(Object.values(doc.recipeRevisions)[0]);
                r.id = 'revision-' + i;
                r.definition.title = 'Version ' + i;
                doc.recipeRevisions[r.id] = r;
            }
            const keys = Object.keys(doc.logs), canvas = document.createElement('canvas');
            canvas.width = 1100;
            canvas.height = 1100;
            const ctx = canvas.getContext('2d');
            for (let n = 0; n < 64; n++) {
                const image = ctx.createImageData(1100, 1100);
                let seed = n + 1;
                for (let i = 0; i < image.data.length; i += 4) {
                    seed = (Math.imul(seed, 1664525) + 1013904223) | 0;
                    image.data[i] = seed & 255;
                    image.data[i + 1] = (seed >>> 8) & 255;
                    image.data[i + 2] = (seed >>> 16) & 255;
                    image.data[i + 3] = 255;
                }
                ctx.putImageData(image, 0, 0);
                const date = keys[n].slice(-10);
                doc.logs[keys[n]].evidences = [{ id: 'photo', kind: 'image', src: canvas.toDataURL('image/jpeg', .66), caption: 'Noise synthetic ' + n, createdAt: date + 'T12:00:00Z' }];
            }
            const png = canvas.toDataURL('image/png');
            doc.logs[keys[64]].evidences = [{ id: 'png', kind: 'image', src: png, caption: 'Large synthetic PNG', createdAt: doc.logs[keys[64]].history.capture.capturedAt }];
            doc.logs[keys[65]].evidences = copy(doc.logs[keys[64]].evidences);
            doc.routines.push({ id: 'new-routine', title: 'New routine', desc: '', steps: [{ id: 'new-step', title: 'Step', min: 30 }] });
            const opts = { factory: indexedDB, legacy: L, schedule: H.schedule, plannerActions: H.plannerActions }, db = H.createLineageDatabase({ ...opts, name: 'fullhouse-lab-events-perf-new', readSources: () => ({ main: null, alias: null }) }), old = H.createLabDatabase({ ...opts, name: 'fullhouse-lab-events-perf-full' });
            let mark = now();
            const plan = await H.storageModel.prepareDocument(doc, L), seedPreparationMs = now() - mark;
            if (plan.images.reduce((n, i) => n + i.size, 0) !== 42175847)
                throw Error('Reference photo corpus changed');
            await db.commit(plan, { id: 'seed' });
            await old.commit(plan, { id: 'seed' });
            const engine = H.createEngine(L), adapter = H.createAdapter(H.schedule), compat = H.createLegacyCompat({ legacy: L, engine, adapter }), oldSession = H.createCompatSession({ database: old, compat, legacy: L, plannerActions: H.plannerActions, engine });
            mark = now();
            await oldSession.open();
            const previousOpenMs = now() - mark;
            mark = now();
            let token = (await db.incremental.openWindow()).token;
            const openMs = now() - mark;
            const contextFor = id => ({ operationId: id, today: '2030-01-07', at: '2030-01-07T12:00:00Z' }), draft = extra => ({ id: '', title: 'New activity', date: '2030-01-08', time: '10:00', minutes: 30, goalId: '', routineId: '', repeat: 'none', note: '', overrides: {}, ...extra });
            mark = now();
            let previousSessionError = null;
            try {
                const attempt = await oldSession.plan('saveEvent', draft(), { ...contextFor('attempt'), ids: ['attempt-event'] });
                if (attempt.pending)
                    previousSessionError = attempt.pending.error;
            }
            catch (e) {
                previousSessionError = e.message;
            }
            const previousAttemptMs = now() - mark;
            if (!previousSessionError)
                throw Error('Previous session now accepts corpus; update comparison');
            const heapBefore = heapSample(), operations = [];
            let full = doc, oldHead = (await old.open()).head;
            for (const [id, payload] of [['point', draft({ goalId: 'goal' })], ['occasion', draft({ kind: 'occasion', date: '2030-02-01', endDate: '2030-02-04' })], ['daily-routine', draft({ routineId: 'new-routine', repeat: 'daily' })]]) {
                mark = now();
                const reservation = await db.incremental.reserveEvent(token, id), reservationMs = now() - mark;
                const ref = H.plannerActions({ ...full, logs: {} }, { ...contextFor(id), ids: [reservation.eventId], confirm: true });
                ref.controller.state.eventDraft = { ...payload, seriesId: reservation.seriesId };
                await ref.controller.saveEvent();
                const candidate = ref.result().candidate;
                if (!candidate)
                    throw Error('Full Planner reference rejected: ' + ref.result().messages.join(';'));
                const next = { ...full, events: candidate.events };
                mark = now();
                const complete = await H.storageModel.prepareDocument(next, L), fullPrepareMs = now() - mark;
                mark = now();
                const slow = await old.commit(complete, { id, expected: oldHead }), fullCommitMs = now() - mark;
                oldHead = slow.head;
                full = next;
                mark = now();
                const op = await db.incremental.prepareEvent(token, reservation, payload, contextFor(id)), prepareMs = now() - mark, metrics = db.incremental.eventMetrics(op);
                let recovered = op, recovery = null;
                if (id === 'point') {
                    mark = now();
                    const file = await db.incremental.exportPending(op, { event: payload }), exportPendingMs = now() - mark;
                    mark = now();
                    const packet = await H.recoveryBinary.inspectRecovery(file, L), inspectPendingMs = now() - mark;
                    mark = now();
                    recovered = await db.incremental.resumePending(token, packet);
                    recovery = { bytes: file.size, exportPendingMs, inspectPendingMs, rebuildPendingMs: now() - mark };
                    if (recovered.id !== op.id) throw Error('Large recovery changed operation identity');
                }
                const saved = await db.incremental.commitEvent(recovered);
                token = saved.token;
                mark = now();
                const view = await db.incremental.readEvent(token, reservation.eventId), readMs = now() - mark;
                if (saved.status !== 'confirmed' || saved.receipt.rootHash !== complete.rootHash || saved.receipt.newImages !== 0 || view.recordCount !== 0)
                    throw Error('Incremental root/history/capture mismatch');
                operations.push({ id, reservationMs, fullPrepareMs, fullCommitMs, prepareMs, ...metrics, transactionMs: saved.transactionMs, lineagePrepareMs: saved.lineagePrepareMs, lineageAfterMs: saved.lineageAfterMs, confirmationMs: saved.confirmationMs, readMs, changedRows: op.changedRows, newImages: saved.receipt.newImages, photoBytesHydrated: view.photoBytesHydrated, recovery });
            }
            const state = await db.open();
            for (const table of ['executions', 'revisions', 'evidence']) {
                const hashes = new Map(plan.tables[table].map(r => [r.key, r.hash]));
                if (state.plan.tables[table].length !== hashes.size || state.plan.tables[table].some(r => hashes.get(r.key) !== r.hash))
                    throw Error('Historical per-key hashes changed');
            }
            await db.auditLineage();
            mark = now();
            const archive = await H.storageArchive.exportArchive(state.plan, L), exportMs = now() - mark;
            mark = now();
            const imported = await H.storageArchive.importArchive(archive, L), importMs = now() - mark;
            const target = H.createLineageDatabase({ ...opts, name: 'fullhouse-lab-events-perf-restored', readSources: () => ({ main: null, alias: null }) });
            mark = now();
            await target.commit(imported, { id: 'restore', confirmRestore: true });
            const restoreMs = now() - mark, restored = await target.open();
            if (restored.head.rootHash !== state.head.rootHash || restored.plan.images.length !== plan.images.length)
                throw Error('Restoration root/images changed');
            for (const image of plan.images) {
                const found = restored.plan.images.find(i => i.hash === image.hash);
                if (!found || found.size !== image.size || await H.storageModel.bytesHash(found.blob) !== image.hash)
                    throw Error('Photo bytes changed');
            }
            const heap = heapSample();
            db.close();
            old.close();
            target.close();
            return { executions: plan.tables.executions.length, revisions: plan.tables.revisions.length, photoBytes: plan.images.reduce((n, i) => n + i.size, 0), images: plan.images.length, seedPreparationMs, previousOpenMs, openMs, previousSessionError, previousAttemptMs, operations, exportMs, importMs, restoreMs, archiveBytes: archive.size, heapBefore, heap, allHistoricalHashesEqual: true, allPhotoBytesVerified: true };
        });
        // Separate window: do not attribute the heap containing full comparisons/archives
        // to an incremental edit. Blobs/native memory and peaks are not measured here.
        const memoryPage = await context.newPage();
        await memoryPage.goto(url + '/storage');
        result.metadataMemory = await memoryPage.evaluate(async () => {
            const heap = () => { globalThis.gc?.(); return performance.memory?.usedJSHeapSize ?? null; };
            const before = heap(), H = FullhouseHistory;
            window.memoryDB = H.createLineageDatabase({ factory: indexedDB, name: 'fullhouse-lab-events-perf-new', legacy: H.schedule.validData, schedule: H.schedule, plannerActions: H.plannerActions, readSources: () => ({ main: null, alias: null }) });
            window.memoryToken = (await memoryDB.incremental.openWindow()).token;
            const after = heap(); memoryDB.close();
            return { beforeJSHeapBytes: before, afterJSHeapBytes: after, deltaJSHeapBytes: before === null ? null : after - before, requestedGC: typeof globalThis.gc === 'function', scope: 'Separate metadata window, retained JS heap only; no peak/native/total-browser measurement' };
        });
        await memoryPage.close();
        assert.deepEqual(errors, []);
        assert.equal(result.photoBytes, 42175847);
        assert.equal(result.executions, 5000);
        assert.equal(result.revisions, 501);
        console.log(JSON.stringify({ base: '13ee9d1', browser: browser.version(), sample: 'single desktop Chromium run; same corpus, full comparator and incremental route; not a phone or total browser RSS', result }, null, 2));
    }
    finally {
        if (browser)
            await browser.close();
        await new Promise(r => server.close(r));
    }
})().catch(e => { console.error(e); process.exitCode = 1; });
