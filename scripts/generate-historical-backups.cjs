// Run from the repository root. Requires the pinned historical Git objects.
// Regenerates synthetic exports through each release's actual shipped writer.
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
process.env.TZ = 'UTC';
const versions = ['01527cc', 'b352429', 'fc7b9ab', 'e7ddcba', 'fc64f09', 'a1bfe58', 'd716246', '3dc1e5b', 'b09c941'];
(async () => {
  for (const [index, ref] of versions.entries()) {
    const commit = execFileSync('git', ['rev-parse', ref], { encoding: 'utf8' }).trim();
    const source = execFileSync('git', ['show', `${commit}:app.js`], { encoding: 'utf8', maxBuffer: 2e6 });
    let exported, counter = 0;
    class FileReader { readAsDataURL() { this.result = 'data:image/png;base64,AA=='; this.onload(); } }
    class Image { constructor() { this.width = 1; this.height = 1; } set src(value) { this.onload(); } }
    const storage = new Map(); const math = Object.create(Math); math.random = () => (++counter) / 100000;
    class Clock extends Date { constructor(...args) { super(...(args.length ? args : [2030, 0, 7, 12])); } static now() { return new Clock().getTime(); } }
    class Component { constructor(props) { this.props = props; } setState(patch) { Object.assign(this.state, typeof patch === 'function' ? patch(this.state) : patch); } }
    const context = vm.createContext({ Date: Clock, Math: math, console, Blob, FileReader, Image, window: {}, setTimeout() {},
      URL: { createObjectURL(blob) { exported = blob; return 'blob:synthetic'; }, revokeObjectURL() {} },
      React: { Component, createElement() {} }, ReactDOM: { render() {} },
      document: { getElementById() {}, createElement(tag) { return tag === 'canvas' ? { getContext() { return { drawImage() {} }; }, toDataURL() { return 'data:image/jpeg;base64,AA=='; } } : { click() {}, remove() {} }; }, body: { appendChild() {} } },
      localStorage: { getItem(key) { return storage.get(key) ?? null; }, setItem(key, value) { storage.set(key, String(value)); } },
    });
    vm.runInContext(source, context, { filename: `${ref}/app.js` });
    const controller = vm.runInContext('new Planner({})', context);
    controller.state.guideOpen = false;
    controller.askConfirm = async () => true;
    controller.state.goalDraft = { ...controller.state.goalDraft, id: '', title: 'Synthetic historical goal', desc: 'Generated by original saveGoal', current: 1, target: 10, unit: 'units' };
    if (index >= 1) controller.state.goalDraft.mode = 'numeric';
    if (index >= 3) Object.assign(controller.state.goalDraft, { area: 'mind', review: { date: '2030-01-07', time: '18:00', repeat: 'weekly' } });
    controller.saveGoal();
    const goal = controller.state.data.goals.at(-1);
    controller.openProgress(goal); controller.state.progressValue = '2.5'; controller.state.progressNote = 'Synthetic recorded progress'; controller.saveProgress();
    controller.state.routineDraft = { ...controller.state.routineDraft, id: '', title: 'Synthetic historical routine', desc: '', steps: [{ id: 'synthetic-step', title: 'Synthetic step', min: 2.5 }] };
    if (index >= 1) controller.state.routineDraft.steps[0].children = [{ id: 'synthetic-child', title: 'Synthetic detail', min: 2.5 }];
    if (index >= 3) controller.state.routineDraft.steps[0].variants = [{ id: 'synthetic-variant', title: 'Synthetic variant', desc: '', min: 3.5, days: [2], children: [{ id: 'synthetic-variant-child', title: 'Synthetic variant detail', min: 3.5 }] }];
    controller.saveRoutine();
    const routine = controller.state.data.routines.at(-1);
    controller.state.eventDraft = { ...controller.state.eventDraft, id: '', title: 'Synthetic historical event', routineId: routine.id, goalId: goal.id, repeat: 'daily', time: '11:00' };
    if (index >= 4) Object.assign(controller.state.eventDraft, { anchor: 'end', endTime: '12:00' });
    await controller.saveEvent();
    const event = controller.state.data.events.at(-1);
    controller.toggleStep(event, '2030-01-07', index >= 1 ? 'synthetic-child' : 'synthetic-step');
    if (index >= 5) controller.saveOccurrenceNote(event, '2030-01-07', 'Synthetic note');
    if (index >= 7) await controller.saveEvidence(event, '2030-01-07', 'synthetic-child', { type: 'image/png', size: 10 });
    if (index >= 7) { controller.state.reviewDraft = 'Synthetic daily review'; controller.saveDayReview(); }
    assert.equal(event.title, 'Synthetic historical event');
    controller.exportData();
    const raw = await exported.text();
    assert.deepEqual(JSON.parse(raw), JSON.parse(storage.get('fullhouse-v01')));
    const fixture = { version: `0.${index + 1}`, commit, scenarios: ['original seed', 'saveGoal', 'saveProgress', 'saveRoutine with fractional minutes', 'saveEvent', 'toggleStep', ...(index >= 5 ? ['saveOccurrenceNote'] : []), ...(index >= 7 ? ['saveEvidence with synthetic image adapter', 'saveDayReview'] : []), 'exportData'], data: JSON.parse(raw) };
    fs.writeFileSync(path.join(__dirname, `../tests/fixtures/historical/v0${index + 1}.json`), JSON.stringify(fixture, null, 2) + '\n');
  }
})().catch(error => { console.error(error); process.exit(1); });
