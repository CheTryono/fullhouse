'use strict';
// Copy only the self-contained PUBLIC v1 validator. No Planner, VM or history/v2.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const start = source.indexOf('function validData(v) {');
const end = source.indexOf('\nfunction occurs(', start);
if (start < 0 || end < start) throw Error('No se encontró el validador público v1');
const output = "'use strict';\n// Generated by scripts/build-remote-validator.cjs from app.js. Do not edit.\n" + source.slice(start, end) + '\nmodule.exports = {validData};\n';
const target = path.join(root, 'remote/v1-validator.cjs');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw Error('Regenerar remote/v1-validator.cjs desde app.js');
  console.log('Remote validator matches the public v1 validator.');
} else fs.writeFileSync(target, output);
